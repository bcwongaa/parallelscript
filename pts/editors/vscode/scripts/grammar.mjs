// Makes syntaxes/ParallelScript.tmLanguage.json from VS Code's TypeScript grammar
// (syntaxes/TypeScript.tmLanguage.json, vendored unchanged): the same rules with every
// scope's `.ts` suffix made `.pts`, and `parallel` a keyword where the parser takes it for
// one (D-O05, D-120): before `for` on the same line, and before a token on the same line
// that starts an expression and can't follow an identifier.
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = new URL("../syntaxes/TypeScript.tmLanguage.json", import.meta.url);
const OUTPUT = new URL("../syntaxes/ParallelScript.tmLanguage.json", import.meta.url);

// `parallel` not inside a longer name or after a member access, as the TS grammar writes its keywords.
const PARALLEL = String.raw`(?<![_$[:alnum:]])(?:(?<=\.\.\.)|(?<!\.))parallel(?![_$[:alnum:]])`;
// Words that start an expression but also follow an identifier (`parallel as T`, `for (parallel of xs)`).
const OPERATOR_WORDS = String.raw`(?:as|satisfies|of|in|instanceof|for)(?![_$[:alnum:]])`;
// The first characters of the tokens that start an expression other than `(`, `[`, a
// template, an operator, `!`, `...` and `.` (a number like `.5` starts one).
const OPERAND_START = String.raw`(?:[_$[:alpha:]]|[0-9]|\.[0-9]|['"{~])`;

const parallelKeyword = {
    patterns: [
        {
            name: "keyword.control.parallel.pts",
            match: String.raw`${PARALLEL}(?=[ \t]+for(?![_$[:alnum:]]))`,
        },
        {
            name: "keyword.control.parallel.pts",
            match: String.raw`${PARALLEL}(?=[ \t]*(?!${OPERATOR_WORDS})${OPERAND_START})`,
        },
    ],
};

/** Every scope in a rule's name ends in `.ts`; ParallelScript's end in `.pts`. */
function renameScopes(node) {
    if (Array.isArray(node)) {
        node.forEach(renameScopes);
        return;
    }
    if (node === null || typeof node !== "object") {
        return;
    }
    for (const [key, value] of Object.entries(node)) {
        if ((key === "name" || key === "contentName") && typeof value === "string") {
            node[key] = value.replace(/\.ts(?=\s|$)/g, ".pts");
        } else {
            renameScopes(value);
        }
    }
}

/** Puts the parallel keyword's rule first in a repository rule's patterns. */
function includeFirst(grammar, ruleName) {
    const rule = grammar.repository[ruleName];
    if (!Array.isArray(rule?.patterns)) {
        throw new Error(`the TypeScript grammar has no patterns for #${ruleName}`);
    }
    rule.patterns.unshift({ include: "#parallel-keyword" });
}

function makeGrammar(typescript) {
    const grammar = structuredClone(typescript);
    renameScopes(grammar.repository);
    renameScopes(grammar.patterns);
    grammar.repository["parallel-keyword"] = parallelKeyword;
    includeFirst(grammar, "statements");
    includeFirst(grammar, "expressionWithoutIdentifiers");
    return {
        information_for_contributors: [
            "Generated by scripts/grammar.mjs from syntaxes/TypeScript.tmLanguage.json (VS Code's TypeScript grammar).",
            "Change the script, not this file.",
        ],
        version: typescript.version,
        name: "ParallelScript",
        scopeName: "source.pts",
        patterns: grammar.patterns,
        repository: grammar.repository,
    };
}

const typescript = JSON.parse(readFileSync(SOURCE, "utf8"));
writeFileSync(OUTPUT, JSON.stringify(makeGrammar(typescript), null, "\t") + "\n");
