func TestStringConstantsKeepTheirExactBytes(t *testing.T) {
	t.Parallel()
	values := []string{
		`quote " backslash \ end`, "tab\tnewline\ncr\r", "??= ??/ ??' trigraphs", "nul\x00byte",
		"héllo wörld", "emoji 😀", "del\x7f c1\u0085 bidi‮", "octal\x01" + "7 digits",
		"lone " + stringutil.EncodeJSStringRune(0xD800) + " surrogate",
	}
	var stmts []ir.Stmt
	var want strings.Builder
	for i, value := range values {
		stmts = append(stmts, logAt(i+1, str(value)))
		// console.log writes a lone surrogate as U+FFFD, as Node does.
		want.WriteString(strings.ReplaceAll(value, stringutil.EncodeJSStringRune(0xD800), "\uFFFD") + "\n")
	}
	assert.Equal(t, run(t, programOf(stmts...)), want.String())
}

