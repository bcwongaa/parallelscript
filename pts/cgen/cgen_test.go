const sourceFile = "/p/main.pts"

func at(line int) ir.Pos { return ir.Pos{File: sourceFile, Line: line} }

// programOf wraps statements in the main function of a program.
func programOf(stmts ...ir.Stmt) *ir.Program {
	return programWithMain(&ir.Func{Name: "main", Pos: at(1), Result: ir.Void, Body: &ir.Block{At: at(1), Stmts: stmts}})
}

// programWithMain is the one-module program whose top-level code is main.
func programWithMain(main *ir.Func) *ir.Program {
	module := &ir.Module{Init: main}
	main.Module = module
	return &ir.Program{Funcs: []*ir.Func{main}, Modules: []*ir.Module{module}, Main: main}
}

// logAt is console.log(args...) on the given line, boxing each argument.
func logAt(line int, args ...ir.Expr) ir.Stmt {
	boxed := make([]ir.Expr, len(args))
	for i, arg := range args {
		boxed[i] = &ir.Box{X: arg}
	}
	return &ir.ExprStmt{At: at(line), X: &ir.CallBuiltin{Builtin: ir.ConsoleLog, Args: boxed}}
}

func str(value string) ir.Expr { return &ir.StringConst{Value: value} }

func num(value float64) ir.Expr { return &ir.NumberConst{Value: value} }

// run compiles the program's C with the runtime and returns what it prints.
func run(t *testing.T, program *ir.Program) string {
	t.Helper()
	tc, err := toolchain.New()
	assert.NilError(t, err)
	rt, err := tc.Runtime(t.Context(), toolchain.Release)
	assert.NilError(t, err)
	dir := t.TempDir()
	cFile := filepath.Join(dir, "main.c")
	assert.NilError(t, os.WriteFile(cFile, []byte(cgen.Emit(program)), 0o644))
	exe := filepath.Join(dir, "main")
	assert.NilError(t, tc.CompileProgram(t.Context(), rt, []string{cFile}, exe))
	out, err := exec.CommandContext(t.Context(), exe).Output()
	assert.NilError(t, err)
	return string(out)
}

