const sourceFile = "/p/main.pts"

func at(line int) ir.Pos { return ir.Pos{File: sourceFile, Line: line} }

// programOf wraps statements in the main function of a program.
func programOf(stmts ...ir.Stmt) *ir.Program {
	main := &ir.Func{Name: "main", Pos: at(1), Result: ir.Void, Body: &ir.Block{At: at(1), Stmts: stmts}}
	return &ir.Program{Funcs: []*ir.Func{main}, Main: main}
}

// logAt is console.log(args...) on the given line, boxing each argument.
func logAt(line int, args ...ir.Expr) ir.Stmt {
	boxed := make([]ir.Expr, len(args))
	for i, arg := range args {
		boxed[i] = &ir.Box{X: arg}
	}
	return &ir.ExprStmt{At: at(line), X: &ir.CallBuiltin{Builtin: ir.ConsoleLog, Args: boxed}}
}

func str(value string) ir.Expr { return &ir.StringConst{Value: value} }

func num(value float64) ir.Expr { return &ir.NumberConst{Value: value} }

// run compiles the program's C with the runtime and returns what it prints.
func run(t *testing.T, program *ir.Program) string {
	t.Helper()
	tc, err := toolchain.New()
	assert.NilError(t, err)
	rt, err := tc.Runtime(t.Context(), toolchain.Release)
	assert.NilError(t, err)
	dir := t.TempDir()
	cFile := filepath.Join(dir, "main.c")
	assert.NilError(t, os.WriteFile(cFile, []byte(cgen.Emit(program)), 0o644))
	exe := filepath.Join(dir, "main")
	assert.NilError(t, tc.CompileProgram(t.Context(), rt, []string{cFile}, exe))
	out, err := exec.CommandContext(t.Context(), exe).Output()
	assert.NilError(t, err)
	return string(out)
}

func TestHelloWorldEmitsReadableC(t *testing.T) {
	t.Parallel()
	got := cgen.Emit(programOf(logAt(1, str("Hello, ParallelScript"))))
	assert.Equal(t, got, `/* Generated by pts from main.pts. */
#include "pts.h"

PTS_STATIC_STRING(pts_str_1, PTS_STRING_ASCII, 21, 21, "Hello, ParallelScript");

static void pts_fn_main(void);

int main(int argc, char **argv) {
  pts_runtime_init(argc, argv);
  pts_fn_main();
  return pts_runtime_exit(0);
}

#line 1 "/p/main.pts"
static void pts_fn_main(void) {
#line 1 "/p/main.pts"
  pts_console_log(1, (pts_value[]){pts_value_from_string(pts_str_1)});
}
`)
	assert.Equal(t, run(t, programOf(logAt(1, str("Hello, ParallelScript")))), "Hello, ParallelScript\n")
}

func TestLineDirectivesAreEmittedOnlyWhenTheLineChanges(t *testing.T) {
	t.Parallel()
	got := cgen.Emit(programOf(logAt(2, num(1)), logAt(3, num(2)), logAt(3, num(3)), logAt(9, num(4))))
	body := got[strings.Index(got, "static void pts_fn_main(void) {"):]
	// The header is line 1 by its #line, so the next C line already counts as line 2.
	assert.Equal(t, body, `static void pts_fn_main(void) {
  pts_console_log(1, (pts_value[]){pts_value_from_number(1.0)});
  pts_console_log(1, (pts_value[]){pts_value_from_number(2.0)});
#line 3 "/p/main.pts"
  pts_console_log(1, (pts_value[]){pts_value_from_number(3.0)});
#line 9 "/p/main.pts"
  pts_console_log(1, (pts_value[]){pts_value_from_number(4.0)});
}
`)
}

func TestLineDirectiveEscapesThePath(t *testing.T) {
	t.Parallel()
	main := &ir.Func{Name: "main", Pos: ir.Pos{File: `/p/a "b"\c.pts`, Line: 1}, Result: ir.Void, Body: &ir.Block{}}
	got := cgen.Emit(&ir.Program{Funcs: []*ir.Func{main}, Main: main})
	assert.Assert(t, strings.Contains(got, `#line 1 "/p/a \"b\"\\c.pts"`), got)
}

func TestStringConstantsKeepTheirExactBytes(t *testing.T) {
	t.Parallel()
	values := []string{
		`quote " backslash \ end`, "tab\tnewline\ncr\r", "??= ??/ ??' trigraphs", "nul\x00byte",
		"héllo wörld", "emoji 😀", "del\x7f c1\u0085 bidi‮", "octal\x01" + "7 digits",
		"lone " + stringutil.EncodeJSStringRune(0xD800) + " surrogate",
	}
	var stmts []ir.Stmt
	var want strings.Builder
	for i, value := range values {
		stmts = append(stmts, logAt(i+1, str(value)))
		// console.log writes a lone surrogate as U+FFFD, as Node does.
		want.WriteString(strings.ReplaceAll(value, stringutil.EncodeJSStringRune(0xD800), "\uFFFD") + "\n")
	}
	assert.Equal(t, run(t, programOf(stmts...)), want.String())
}

func TestStringConstantsCarryLengthAndASCIIFlag(t *testing.T) {
	t.Parallel()
	got := cgen.Emit(programOf(logAt(1, str("abc"), str("héllo"), str("😀"), str(stringutil.EncodeJSStringRune(0xDC00)), str("abc"))))
	assert.Assert(t, strings.Contains(got, `PTS_STATIC_STRING(pts_str_1, PTS_STRING_ASCII, 3, 3, "abc");`), got)
	assert.Assert(t, strings.Contains(got, `PTS_STATIC_STRING(pts_str_2, 0, 6, 5, "héllo");`), got)
	assert.Assert(t, strings.Contains(got, `PTS_STATIC_STRING(pts_str_3, 0, 4, 2, "😀");`), got)
	assert.Assert(t, strings.Contains(got, `PTS_STATIC_STRING(pts_str_4, 0, 3, 1, "\355\260\200");`), got)
	assert.Assert(t, !strings.Contains(got, "pts_str_5"), "equal constants are shared:\n%s", got)
}

func TestNumberConstantsRoundTripExactly(t *testing.T) {
	t.Parallel()
	values := []float64{0, math.Copysign(0, -1), 1, 0.1, 1e21, 123456789012345680000, 5e-324, math.MaxFloat64,
		math.NaN(), math.Inf(1), math.Inf(-1), -2.5}
	args := make([]ir.Expr, len(values))
	for i, v := range values {
		args[i] = num(v)
	}
	got := run(t, programOf(logAt(1, args...)))
	assert.Equal(t, got, "0 -0 1 0.1 1e+21 123456789012345680000 5e-324 1.7976931348623157e+308 NaN Infinity -Infinity -2.5\n")
}

func TestLocalsKeepSourceNamesUnlessCForbidsThem(t *testing.T) {
	t.Parallel()
	names := []string{"greeting", "int", "main", "pts_x", "_hidden", "MAX", "a$b", "café", "greeting"}
	var stmts []ir.Stmt
	var refs []ir.Expr
	for i, name := range names {
		local := &ir.Local{Name: name, Type: ir.Number}
		stmts = append(stmts, &ir.LocalDecl{At: at(i + 1), Local: local, Init: num(float64(i))})
		refs = append(refs, &ir.LocalRef{Local: local})
	}
	stmts = append(stmts, logAt(len(names)+1, refs...))
	program := programOf(stmts...)

	got := cgen.Emit(program)
	for _, decl := range []string{"double greeting = 0.0;", "double int_ = 1.0;", "double main_ = 2.0;", "double pts_x_ = 3.0;",
		"double _hidden_ = 4.0;", "double MAX_ = 5.0;", "double a_Sb_ = 6.0;", "double caf_u00E9_ = 7.0;", "double greeting_2 = 8.0;"} {
		assert.Assert(t, strings.Contains(got, decl), "missing %q in:\n%s", decl, got)
	}
	assert.Equal(t, run(t, program), "0 1 2 3 4 5 6 7 8\n")
}

func TestEveryPrimitiveTypeCanBeAStoredLocal(t *testing.T) {
	t.Parallel()
	locals := []*ir.Local{{Name: "n", Type: ir.Number}, {Name: "b", Type: ir.Bool}, {Name: "s", Type: ir.String},
		{Name: "u", Type: ir.Undefined}, {Name: "z", Type: ir.Null}}
	inits := []ir.Expr{num(1.5), &ir.BoolConst{Value: true}, str("text"), &ir.UndefinedConst{}, &ir.NullConst{}}
	var stmts []ir.Stmt
	var refs []ir.Expr
	for i, local := range locals {
		stmts = append(stmts, &ir.LocalDecl{At: at(i + 1), Local: local, Init: inits[i]})
		refs = append(refs, &ir.LocalRef{Local: local})
	}
	nested := &ir.Block{At: at(6), Stmts: []ir.Stmt{logAt(7, refs...)}}
	assert.Equal(t, run(t, programOf(append(stmts, nested, logAt(8))...)), "1.5 true text undefined null\n\n")
}

func binary(op ir.BinaryOp, x ir.Expr, y ir.Expr) ir.Expr { return &ir.Binary{Op: op, X: x, Y: y} }

func TestOperatorsEmitParenthesizedC(t *testing.T) {
	t.Parallel()
	expr := binary(ir.Lt, binary(ir.Add, num(1), &ir.Unary{Op: ir.Neg, X: num(2)}), binary(ir.Rem, num(7), binary(ir.Pow, num(2), num(3))))
	got := cgen.Emit(programOf(logAt(1, expr)))
	assert.Assert(t, strings.Contains(got, "pts_value_from_bool(((1.0 + (-2.0)) < pts_number_rem(7.0, pts_number_pow(2.0, 3.0))))"), got)
}

func TestNumberOperatorsFollowJavaScript(t *testing.T) {
	t.Parallel()
	nan, inf, negZero := num(math.NaN()), num(math.Inf(1)), num(math.Copysign(0, -1))
	program := programOf(
		logAt(1, binary(ir.Add, num(0.1), num(0.2)), binary(ir.Sub, num(0), num(0)), binary(ir.Mul, negZero, num(5)),
			binary(ir.Div, num(1), negZero), binary(ir.Div, num(0), num(0))),
		logAt(2, binary(ir.Rem, num(-5.5), num(2)), binary(ir.Rem, num(5), inf), binary(ir.Rem, negZero, num(3)), binary(ir.Rem, num(1), num(0))),
		logAt(3, binary(ir.Pow, num(2), num(0.5)), binary(ir.Pow, num(1), inf), binary(ir.Pow, nan, num(0)), binary(ir.Pow, negZero, num(-1))),
		logAt(4, binary(ir.Eq, nan, nan), binary(ir.Ne, nan, nan), binary(ir.Eq, num(0), negZero), binary(ir.Lt, nan, num(1)), binary(ir.Ge, inf, inf)),
		logAt(5, binary(ir.Eq, &ir.BoolConst{Value: true}, &ir.BoolConst{Value: true}), &ir.Unary{Op: ir.Neg, X: num(0)}),
	)
	assert.Equal(t, run(t, program), `0.30000000000000004 0 -0 -Infinity NaN
-1.5 5 -0 NaN
1.4142135623730951 NaN 1 -Infinity
false true true false true
true -0
`)
}

func TestStringOperationsFollowJavaScript(t *testing.T) {
	t.Parallel()
	toStr := func(x ir.Expr) ir.Expr { return &ir.ToString{X: x} }
	length := func(x ir.Expr) ir.Expr { return &ir.CallBuiltin{Builtin: ir.StringLength, Args: []ir.Expr{x}} }
	program := programOf(
		logAt(1, binary(ir.Concat, str("n="), toStr(num(0.5))), binary(ir.Concat, toStr(&ir.BoolConst{Value: false}), toStr(&ir.NullConst{})),
			toStr(&ir.UndefinedConst{}), toStr(&ir.IntConst{Bits: 1 << 63, Ty: ir.U64}), toStr(&ir.IntConst{Bits: 1<<64 - 5, Ty: ir.I8})),
		logAt(2, length(str("héllo😀")), binary(ir.Eq, str("a"), binary(ir.Concat, str(""), str("a"))), binary(ir.Ne, str("a"), str("b")),
			binary(ir.Lt, str("😀"), str("\uffff")), binary(ir.Ge, str("b"), str("abc")), &ir.Unary{Op: ir.Not, X: &ir.BoolConst{Value: true}}),
		logAt(3, binary(ir.Concat, str("\xed\xa0\xbd"), str("\xed\xb8\x80"))),
	)
	assert.Equal(t, run(t, program), "n=0.5 falsenull undefined 9223372036854775808 -5\n7 true true true true false\n😀\n")
}

func TestStringBuiltinsCallTheRuntime(t *testing.T) {
	t.Parallel()
	call := func(builtin *ir.Builtin, args ...ir.Expr) ir.Expr {
		return &ir.CallBuiltin{Builtin: builtin, Args: args}
	}
	box := func(x ir.Expr) ir.Expr { return &ir.Box{X: x} }
	text := str("Héllo")
	program := programOf(
		logAt(1, call(ir.StringElement, text, num(1)), call(ir.StringElement, text, num(9)), box(call(ir.StringElementChecked, text, num(4))),
			box(call(ir.StringElementEquals, text, num(0), str("H"))), box(call(ir.StringCharCodeAt, text, num(1)))),
		logAt(2, box(call(ir.StringSlice, text, num(-3), num(math.Inf(1)))), box(call(ir.StringIndexOf, text, str("l"), num(math.NaN()))),
			box(call(ir.StringToUpperCase, text)), box(call(ir.StringPadStart, str("7"), num(3), str("0"))), box(call(ir.StringRepeat, str("ab"), num(2)))),
		logAt(3, box(&ir.ToString{X: call(ir.StringElement, text, num(9))})),
	)
	assert.Equal(t, run(t, program), "é undefined o true 233\nllo 2 HÉLLO 007 abab\nundefined\n")
}

func TestOperandsWithEffectsAreEvaluatedLeftToRight(t *testing.T) {
	t.Parallel()
	x := &ir.Local{Name: "x", Type: ir.Number}
	ref := &ir.LocalRef{Local: x}
	program := programOf(
		&ir.LocalDecl{At: at(1), Local: x, Init: num(1)},
		logAt(2, binary(ir.Add, ref, &ir.Assign{Local: x, Value: num(5)}), ref,
			&ir.Assign{Local: x, Value: binary(ir.Mul, ref, num(2)), Postfix: true}, ref),
	)
	source := cgen.Emit(program)
	assert.Assert(t, strings.Contains(source, "pts_tmp"), source)
	assert.Equal(t, run(t, program), "6 5 5 10\n")
}

func TestLabelsAreWrittenOnlyWhereAGotoJumps(t *testing.T) {
	t.Parallel()
	inner, outer := &ir.Label{}, &ir.Label{Name: "outer"}
	loop := func(label *ir.Label, body ...ir.Stmt) ir.Stmt {
		return &ir.Loop{At: at(1), Label: label, Body: &ir.Block{At: at(1), Stmts: body}}
	}
	program := programOf(
		loop(outer, loop(inner, &ir.Break{At: at(2), Target: outer}), &ir.Break{At: at(3), Target: outer}),
		logAt(4, str("done")),
	)
	source := cgen.Emit(program)
	assert.Assert(t, strings.Contains(source, "goto outer_break;") && strings.Contains(source, "outer_break: ;"), source)
	assert.Assert(t, !strings.Contains(source, "_continue: ;") && !strings.Contains(source, "loop_break: ;"), source)
	assert.Equal(t, run(t, program), "done\n")
}
