// Generates pts/runtime/src/collation_tables.h: the collation weights behind
// String.prototype.localeCompare, taken from this Node's ICU so that ParallelScript
// orders strings as Node's default collator does (D-082).
//
//   node pts/runtime/gen/collation_tables.mjs > pts/runtime/src/collation_tables.h
//
// Every code point in the table's blocks gets three weights: its rank among the
// primary (base letter) differences, and its rank among the secondary (accent) and
// tertiary (case and variant) differences inside its primary, and secondary, group.
// Weight 0 means the code point is ignorable at that level. Sorting every code point
// with the collator and grouping neighbours at each strength gives the ranks.
// Code points outside the blocks are Hangul syllables (decomposed into their jamo in
// code) or take implicit weights in code point order (Han first), as ICU does.

const BLOCKS = [
  [0x0000, 0x33ff], // through CJK symbols, Hangul jamo and compatibility jamo
  [0xa000, 0xabff], // Yi, Lisu, Vai, Cyrillic and Latin extensions, Hangul jamo extended-A
  [0xd7b0, 0xd7ff], // Hangul jamo extended-B
  [0xfb00, 0xfffd], // presentation forms, halfwidth and fullwidth forms, specials
  [0x1f000, 0x1faff], // game symbols, emoji and pictographs
];

const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;
const hex = (n, width) => n.toString(16).toUpperCase().padStart(width, "0");

const variant = new Intl.Collator(undefined, { sensitivity: "variant" });
const accent = new Intl.Collator(undefined, { sensitivity: "accent" });
const base = new Intl.Collator(undefined, { sensitivity: "base" });

function weights() {
  const strings = [""];
  for (const [first, last] of BLOCKS) {
    for (let cp = first; cp <= last; cp++) {
      if (!isSurrogate(cp)) strings.push(String.fromCodePoint(cp));
    }
  }
  const sorted = strings.sort(variant.compare);
  const result = new Map();
  let primary = 0, secondary = 1, tertiary = 1;
  sorted.forEach((s, i) => {
    if (i > 0) {
      const previous = sorted[i - 1];
      if (base.compare(previous, s) !== 0) {
        primary++, secondary = 1, tertiary = 1;
      } else if (accent.compare(previous, s) !== 0) {
        secondary++, tertiary = 1;
      } else if (variant.compare(previous, s) !== 0) {
        tertiary++;
      }
    }
    const w = [
      base.compare(s, "") === 0 ? 0 : primary,
      accent.compare(s, "") === 0 ? 0 : secondary,
      variant.compare(s, "") === 0 ? 0 : tertiary,
    ];
    if (w[0] > 0xffff || w[1] > 0xff || w[2] > 0xff) throw new Error(`U+${hex(s.codePointAt(0) ?? 0, 4)}'s weights ${w} don't fit`);
    if (s !== "") result.set(s.codePointAt(0), w);
  });
  return result;
}

function emit() {
  const table = weights();
  const out = [];
  out.push("/*");
  out.push(` * Generated by pts/runtime/gen/collation_tables.mjs from ICU ${process.versions.icu}`);
  out.push(` * (Unicode ${process.versions.unicode}, Node ${process.version}). Do not edit.`);
  out.push(" *");
  out.push(" * Each entry packs a code point's collation weights as primary << 16 |");
  out.push(" * secondary << 8 | tertiary (D-082). Included only by collation.c.");
  out.push(" */");
  out.push(`#define PTS_COLLATION_TABLES_ICU_VERSION "${process.versions.icu}"`);
  out.push("");
  BLOCKS.forEach(([first, last], b) => {
    out.push(`static const uint32_t collation_block_${b}[] = {`);
    for (let row = first; row <= last; row += 8) {
      const cells = [];
      for (let cp = row; cp < row + 8 && cp <= last; cp++) {
        const w = isSurrogate(cp) ? [0, 0, 0] : table.get(cp);
        cells.push(`0x${hex((w[0] << 16) | (w[1] << 8) | w[2], 8)}`);
      }
      out.push(`  ${cells.join(", ")},`);
    }
    out.push("};");
    out.push("");
  });
  out.push("static const collation_block collation_blocks[] = {");
  BLOCKS.forEach(([first, last], b) => out.push(`  {0x${hex(first, 5)}, 0x${hex(last, 5)}, collation_block_${b}},`));
  out.push("};");
  console.log(out.join("\n"));
}

emit();
