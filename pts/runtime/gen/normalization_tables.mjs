// Generates pts/runtime/src/normalization_tables.h: the data behind
// String.prototype.normalize, taken from this Node's ICU so that ParallelScript
// normalizes exactly as Node does (D-135).
//
//   node pts/runtime/gen/normalization_tables.mjs > pts/runtime/src/normalization_tables.h
//
// Regenerate when Node's Unicode version changes; the normalization parts of
// TestGeneratedStringCorpusMatchesNode fail until then.
//
// ICU doesn't expose canonical combining classes, so the table holds their ranks, found by
// asking NFD whether two marks change places: canonical ordering only compares classes,
// so ranks in the same order (equal where the classes are) normalize alike.

const MAX_CODE_POINT = 0x10ffff;
const OVERLAY = 0x334; // combining class 1, the lowest a mark has
const ACUTE = 0x301; // combining class 230

const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;
const isHangulSyllable = (cp) => cp >= 0xac00 && cp <= 0xd7a3; // decomposed and composed by arithmetic
const chars = (...cps) => String.fromCodePoint(...cps);
const codePoints = (string) => [...string].map((c) => c.codePointAt(0));
const hex = (cp) => cp.toString(16).toUpperCase().padStart(4, "0");

const all = [];
for (let cp = 0; cp <= MAX_CODE_POINT; cp++) {
  if (!isSurrogate(cp) && !isHangulSyllable(cp)) all.push(cp);
}

// The full canonical and compatibility decompositions of the code points that have them.
const canonical = [];
const compatibility = [];
for (const cp of all) {
  const nfd = chars(cp).normalize("NFD");
  const nfkd = chars(cp).normalize("NFKD");
  if (nfd !== chars(cp)) canonical.push([cp, codePoints(nfd)]);
  if (nfkd !== nfd) compatibility.push([cp, codePoints(nfkd)]);
}

// reorders reports whether canonical ordering swaps a followed by b: a's class is above b's, b's not 0.
const reorders = (a, b) => chars(a, b).normalize("NFD") !== chars(a, b);
const decomposes = new Set(canonical.map(([cp]) => cp));
const marks = all.filter((cp) => !decomposes.has(cp) && (reorders(cp, OVERLAY) || reorders(ACUTE, cp)));
const compareClasses = (a, b) => (reorders(a, b) ? 1 : reorders(b, a) ? -1 : 0);
marks.sort(compareClasses);
const ranks = new Map();
let rank = 0;
marks.forEach((cp, i) => {
  if (i === 0 || compareClasses(marks[i - 1], cp) !== 0) rank++;
  ranks.set(cp, rank);
});
if (rank > 255) throw new Error(`${rank} combining classes`);
const rankRanges = [];
for (const cp of [...marks].sort((a, b) => a - b)) {
  const last = rankRanges[rankRanges.length - 1];
  if (last && last[1] === cp - 1 && last[2] === ranks.get(cp)) last[1] = cp;
  else rankRanges.push([cp, cp, ranks.get(cp)]);
}

// The primary composites: what NFC makes of a starter (or composite) and the character
// after it. Each is found by splitting its decomposition into the last character it
// composes with and what composes before that.
const compositions = [];
for (const [cp, nfd] of canonical) {
  if (chars(cp).normalize("NFC") !== chars(cp)) continue; // excluded from composition
  let pair = null;
  for (let j = nfd.length - 1; j >= 0 && pair === null; j--) {
    const first = codePoints(chars(...nfd.filter((_, k) => k !== j)).normalize("NFC"));
    if (first.length === 1 && chars(first[0], nfd[j]).normalize("NFC") === chars(cp)) pair = [first[0], nfd[j]];
  }
  if (pair === null) throw new Error(`no pair composes U+${hex(cp)}`);
  compositions.push([pair[0], pair[1], cp]);
}
compositions.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

// The decomposition tables share one pool of code points.
const pool = [];
const entries = (table) =>
  table.map(([cp, mapping]) => {
    const start = pool.length;
    pool.push(...mapping);
    return `  {0x${hex(cp)}, ${start}, ${mapping.length}},`;
  });
const canonicalEntries = entries(canonical);
const compatibilityEntries = entries(compatibility);

const lines = [
  `/* Generated by pts/runtime/gen/normalization_tables.mjs from Node ${process.version} (Unicode ${process.versions.unicode}); do not edit. */`,
  "",
  "/* The code points of every decomposition, which the tables below index. */",
  `static const uint32_t decomposition_pool[${pool.length}] = {`,
];
for (let i = 0; i < pool.length; i += 12) {
  lines.push("  " + pool.slice(i, i + 12).map((cp) => `0x${hex(cp)},`).join(" "));
}
lines.push(
  "};",
  "",
  "/* Full canonical decompositions (NFD of each code point), by code point; Hangul syllables are arithmetic. */",
  `static const decomposition canonical_decompositions[${canonical.length}] = {`,
  ...canonicalEntries,
  "};",
  "",
  "/* Full compatibility decompositions (NFKD), of the code points whose NFKD isn't their NFD. */",
  `static const decomposition compatibility_decompositions[${compatibility.length}] = {`,
  ...compatibilityEntries,
  "};",
  "",
  "/* The ranks of the canonical combining classes other than 0, by code point range. */",
  `static const class_range combining_classes[${rankRanges.length}] = {`,
  ...rankRanges.map(([first, last, r]) => `  {0x${hex(first)}, 0x${hex(last)}, ${r}},`),
  "};",
  "",
  "/* Primary composites by the two characters that compose them, in order; Hangul's are arithmetic. */",
  `static const composition compositions[${compositions.length}] = {`,
  ...compositions.map(([first, second, cp]) => `  {0x${hex(first)}, 0x${hex(second)}, 0x${hex(cp)}},`),
  "};",
);
console.log(lines.join("\n"));
