// Generates pts/runtime/src/case_tables.h: the case mappings and properties behind
// String.prototype.toUpperCase and toLowerCase, taken from this Node's ICU so that
// ParallelScript maps case exactly as Node does (D-016).
//
//   node pts/runtime/gen/case_tables.mjs > pts/runtime/src/case_tables.h
//
// Regenerate when Node's Unicode version changes; TestGeneratedCaseMappingMatchesNode
// fails until then.

const MAX_CODE_POINT = 0x10ffff;
const MAX_MAPPING_LENGTH = 3; // SpecialCasing.txt's longest full mapping

const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;

function codePoints(string) {
  return [...string].map((c) => c.codePointAt(0));
}

// mappings lists every code point from 0x80 up that `convert` changes, with what it becomes.
function mappings(convert) {
  const result = [];
  for (let cp = 0x80; cp <= MAX_CODE_POINT; cp++) {
    if (isSurrogate(cp)) continue;
    const mapped = codePoints(convert(String.fromCodePoint(cp)));
    if (mapped.length === 1 && mapped[0] === cp) continue;
    if (mapped.length > MAX_MAPPING_LENGTH) throw new Error(`U+${hex(cp)} maps to ${mapped.length} code points`);
    result.push([cp, mapped]);
  }
  return result;
}

// ranges lists the code points matching a Unicode property as [first, last] pairs.
function ranges(property) {
  const regex = new RegExp(`^\\p{${property}}$`, "u");
  const result = [];
  for (let cp = 0; cp <= MAX_CODE_POINT; cp++) {
    if (isSurrogate(cp) || !regex.test(String.fromCodePoint(cp))) continue;
    const last = result[result.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp;
    else result.push([cp, cp]);
  }
  return result;
}

function checkAscii() {
  for (let cp = 0; cp < 0x80; cp++) {
    const c = String.fromCharCode(cp);
    const upper = cp >= 0x61 && cp <= 0x7a ? String.fromCharCode(cp - 32) : c;
    const lower = cp >= 0x41 && cp <= 0x5a ? String.fromCharCode(cp + 32) : c;
    if (c.toUpperCase() !== upper || c.toLowerCase() !== lower) throw new Error(`ASCII U+${hex(cp)} maps unexpectedly`);
  }
}

const hex = (cp) => cp.toString(16).toUpperCase().padStart(4, "0");

function mappingTable(name, entries) {
  const rows = entries.map(([cp, mapped]) => `  {0x${hex(cp)}, {${mapped.map((m) => `0x${hex(m)}`).join(", ")}}},`);
  return `static const case_mapping ${name}[] = {\n${rows.join("\n")}\n};\n`;
}

function rangeTable(name, entries) {
  const rows = entries.map(([first, last]) => `  {0x${hex(first)}, 0x${hex(last)}},`);
  return `static const code_point_range ${name}[] = {\n${rows.join("\n")}\n};\n`;
}

checkAscii();
const versions = process.versions;
process.stdout.write(`/*
 * Generated by pts/runtime/gen/case_tables.mjs from Unicode ${versions.unicode}
 * (ICU ${versions.icu}, Node ${process.version}). Do not edit.
 *
 * Full case mappings of every code point from U+0080 up that changes, sorted by
 * code point; ASCII is handled in code. Cased and Case_Ignorable decide
 * Final_Sigma. Included only by string_case.c.
 */
#define PTS_CASE_TABLES_UNICODE_VERSION "${versions.unicode}"

`);
process.stdout.write(mappingTable("upper_mappings", mappings((s) => s.toUpperCase())) + "\n");
process.stdout.write(mappingTable("lower_mappings", mappings((s) => s.toLowerCase())) + "\n");
process.stdout.write(rangeTable("cased_ranges", ranges("Cased")) + "\n");
process.stdout.write(rangeTable("case_ignorable_ranges", ranges("Case_Ignorable")));
