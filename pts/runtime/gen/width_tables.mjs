// Generates pts/runtime/src/width_tables.h: how many terminal columns each code point
// takes, as Node's util.inspect measures it (getStringWidth, through ICU's East Asian
// Width and emoji properties) when it lays out the elements of an array in columns (D-088).
//
//   node --expose-internals pts/runtime/gen/width_tables.mjs > pts/runtime/src/width_tables.h
//
// Regenerate when Node's Unicode version changes.

import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { getStringWidth } = require("internal/util/inspect");

const MAX_CODE_POINT = 0x10ffff;

const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;

// ranges lists the code points whose width isn't 1 as [first, last, width], merging
// neighbours of the same width; surrogates join the ranges around them.
function ranges() {
  const result = [];
  for (let cp = 0; cp <= MAX_CODE_POINT; cp++) {
    if (isSurrogate(cp)) continue;
    const width = getStringWidth(String.fromCodePoint(cp), false);
    if (width === 1) continue;
    const last = result[result.length - 1];
    if (last && last[2] === width && (last[1] === cp - 1 || (last[1] === 0xd7ff && cp === 0xe000))) last[1] = cp;
    else result.push([cp, cp, width]);
  }
  return result;
}

const hex = (cp) => cp.toString(16).toUpperCase().padStart(4, "0");

const lines = [
  "/*",
  ` * Generated by pts/runtime/gen/width_tables.mjs from ICU ${process.versions.icu}`,
  ` * (Unicode ${process.versions.unicode}, Node ${process.version}). Do not edit.`,
  " *",
  " * The code points whose width in a terminal isn't one column, as Node's getStringWidth",
  " * counts them, in ranges sorted by code point (D-088). Included only by inspect.c.",
  " */",
  "",
  "typedef struct width_range {",
  "  uint32_t first, last;",
  "  uint8_t width;",
  "} width_range;",
  "",
  "static const width_range width_ranges[] = {",
];
for (const [first, last, width] of ranges()) {
  lines.push(`  {0x${hex(first)}, 0x${hex(last)}, ${width}},`);
}
lines.push("};", "");
process.stdout.write(lines.join("\n"));
